export const getTaskById = (id: string): GameTask | undefined => {
  return TASKS.find(task => task.id === id);
};

export const getTasksByDifficulty = (difficulty: string): GameTask[] => {
  return TASKS.filter(task => task.difficulty === difficulty);
};

export const getRandomTasks = (count: number, difficulty?: string): GameTask[] => {
  let pool = [...TASKS];
  if (difficulty) {
    pool = pool.filter(task => task.difficulty === difficulty);
  }
  const shuffled = pool.sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
};
