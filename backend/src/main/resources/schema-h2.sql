-- H2 兼容 schema，MODE=MySQL

CREATE TABLE IF NOT EXISTS store (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_name VARCHAR(100) NOT NULL,
    address VARCHAR(500),
    manager_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    real_name VARCHAR(50) NOT NULL,
    role VARCHAR(30) NOT NULL,
    store_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS car_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_vin VARCHAR(50) NOT NULL UNIQUE,
    plate_number VARCHAR(20),
    brand VARCHAR(50) NOT NULL,
    model VARCHAR(100) NOT NULL,
    mileage DECIMAL(12,2),
    register_date DATE,
    assessor_id BIGINT,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING_LISTING',
    source_library_delay BOOLEAN NOT NULL DEFAULT FALSE,
    detector_missing BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS listing_funnel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id BIGINT NOT NULL,
    stage VARCHAR(30) NOT NULL,
    completed_at TIMESTAMP,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    remark VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS finance_approval_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    effective_date DATE NOT NULL,
    approval_rate_min DECIMAL(5,4) NOT NULL,
    approval_rate_max DECIMAL(5,4) NOT NULL,
    remark VARCHAR(500),
    changed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS quotation_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id BIGINT NOT NULL,
    price DECIMAL(15,2) NOT NULL,
    quoted_by BIGINT NOT NULL,
    quoted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valid_days INT NOT NULL DEFAULT 7
);

CREATE TABLE IF NOT EXISTS finance_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id BIGINT NOT NULL,
    doc_type VARCHAR(30) NOT NULL,
    is_missing BOOLEAN NOT NULL DEFAULT TRUE,
    missing_reason VARCHAR(500),
    uploaded_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS vehicle_archive (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id BIGINT NOT NULL UNIQUE,
    archive_data CLOB,
    is_complete BOOLEAN NOT NULL DEFAULT FALSE,
    saved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS review_note (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id BIGINT NOT NULL,
    stage VARCHAR(30),
    note_content CLOB NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS share_link (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_token VARCHAR(100) NOT NULL UNIQUE,
    created_by BIGINT NOT NULL,
    role_scope VARCHAR(255),
    expire_at TIMESTAMP NOT NULL,
    view_count INT NOT NULL DEFAULT 0,
    include_sensitive BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS inventory_turnover (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id BIGINT NOT NULL,
    days_in_inventory INT NOT NULL,
    turnover_stage VARCHAR(30),
    calculated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS data_anomaly (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id BIGINT NOT NULL,
    anomaly_type VARCHAR(50) NOT NULL,
    description VARCHAR(500),
    start_date TIMESTAMP NOT NULL,
    end_date TIMESTAMP,
    resolved BOOLEAN NOT NULL DEFAULT FALSE
);
